CREATE TABLE LAB_DETAILS (
    ASSET_ID               VARCHAR2(50) PRIMARY KEY,
    EQUIPMENT_TYPE         VARCHAR2(100),
    EQUIPMENT_CONDITION    VARCHAR2(100),
    LAST_CALIBRATION_DATE  DATE,
    CONSTRAINT FK_LAB_ASSET FOREIGN KEY (ASSET_ID) 
