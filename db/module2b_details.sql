CREATE TABLE FURNITURE_DETAILS (
    ASSET_ID         VARCHAR2(50) PRIMARY KEY,
    FURNITURE_TYPE   VARCHAR2(100),
    MATERIAL         VARCHAR2(100),
    QUANTITY         NUMBER(6) CHECK (QUANTITY IS NULL OR QUANTITY > 0),
    CONSTRAINT FK_FURN_ASSET FOREIGN KEY (ASSET_ID) 
        REFERENCES ASSETS(ASSET_ID) ON DELETE CASCADE
